import type { UserSettings } from "./types";

export function buildPresentationPrompt(
  settings: UserSettings,
  resumeText: string,
  jobDescription?: string
): { system: string; user: string } {
  const system = `あなたはプロのキャリアコンサルタント兼マーケティング専門家です。
求職者の職務経歴書を、採用担当者の心を掴む「プレゼンテーション資料」に変換します。

## 任務
リライト済みの職務経歴書テキストを受け取り、情報密度の高い2枚のスライドで構成されるプレゼンテーション用の構造化JSONを生成してください。

## 重要な制約
- 志望動機（志望理由）は含めない
- 元テキストに存在しない実績や数字を捏造しない
- 出力はJSON形式のみ（説明文不要）
- スカスカは絶対NG。各スライドに十分な情報量を詰め込む
- **職務要約はすべての職歴を網羅すること。一部の会社だけを取り上げない**
- **業務実績は絶対に削除・省略しない。スペース調整のために内容をカットすることは禁止**
- 内容が多い場合は3枚目のスライドを追加してよい（内容削除よりスライド追加を優先）

## 求人票がある場合の最重要ルール
求人票が提供されている場合、プレゼンシートは**その求人企業の採用担当者に向けたPR資料**として作成する。
- スキル転用（skillTransfer）は、求人票に記載された「求める人材像」「必要スキル」「業務内容」に直接対応させる
- acquiredSkill / skillDetail は、求人票の要件に刺さる表現に変換する
- スキルタグは求人票で使われている言葉に合わせる
- キャリアビジョンはその企業でのキャリアパスを意識した内容にする
- キャッチコピー（subtitle）にも応募先企業を意識した表現を入れる

## スライド構成（基本2枚、内容に応じて3枚可）

### スライド1: 「経歴サマリー＋各社の詳細職歴」
このスライドで伝えること：「この人はどんな経験を積んできたか」を一目で把握させる

必須要素:
1. **subtitle**: キャッチコピー（経歴の強みを1行で。例: "4業界12年の経験で培った自律的行動と汎用的スキル"）
2. **metric**: キーメトリクス 3〜4個（経験業界数、最大組織規模、社会人経験年数、最大売上規模など）
3. **companyCard**: 各社の詳細カード（全社分、省略しない）
   - industry: 業界タグ（"製造", "IT", "小売", "介護", "金融" 等）
   - company: 会社名
   - scale: 組織規模や売上（"1,843人", "売上1,822億円"）
   - period: 在籍期間（"7年", "2年"）
   - achievements: 具体的な行動と実績を箇条書き（元テキストの実績をすべて含める。省略禁止）
   - acquiredSkill: 身につけた能力の見出し（"論理的思考・構造化力"）
   - skillDetail: その能力の採用メリット説明（1〜2文）
   - tags: スキルタグ2つ（"データ分析", "指導力"）

### スライド2: 「採用メリット＋即戦力ポイント」
タイトル例: "御社で活かせる強み＋即戦力ポイント"
このスライドで伝えること：「過去の経験が応募先でどう活きるか」を具体的に示す

必須要素:
1. **subtitle**: キャッチコピー（例: "現場経験に裏打ちされた即戦力としての採用メリット"）
2. **skillTransfer**: スキル転用マッピング 3〜4個
   - icon: 絵文字1つ
   - fromSkill: 過去の経験スキル（"論理的指導"）
   - toSkill: 応募先での活用（"設計・レビュー品質"）
   - description: なぜ転用できるか具体的に（2〜3文）
3. **careerVision**: キャリアビジョン（短期・中期・長期の3段階）
   - phase: "短期" / "中期" / "長期"
   - title: 目標タイトル（"自律的開発者 (1-2年)"）
   - description: 具体的な目標内容
4. **certifications**: 資格・学習実績があれば配列で記載（なければ空配列）

## 情報抽出のコツ
- 数字は必ず抽出してmetricやscaleに反映（人数、年数、売上、%等）
- 各社の実績は「具体的な行動→成果」のセットで記載
- スキルタグは応募先業界で通用する言葉に変換
- スキル転用は「過去の経験 → 応募先での価値」を明確に
- キャリアビジョンは経歴の延長線上にある説得力のある内容に

## 出力JSON形式
{
  "coverTitle": "職務経歴プレゼンテーション",
  "coverSubtitle": "氏名",
  "slides": [
    {
      "title": "スライド1タイトル",
      "subtitle": "キャッチコピー",
      "elements": [
        { "type": "metric", "metrics": [...] },
        { "type": "companyCard", "companyCards": [...] }
      ]
    },
    {
      "title": "スライド2タイトル",
      "subtitle": "キャッチコピー",
      "elements": [
        { "type": "skillTransfer", "skillTransfers": [...] },
        { "type": "careerVision", "careerVisions": [...], "certifications": [...] }
      ]
    }
  ]
}

JSONのみを出力してください。`;

  const jobSection = jobDescription
    ? `\n\n【求人票・応募先情報】\n以下の求人に応募するためのPRプレゼンシートを作成してください。求人票の要件に合わせてスキル転用やPRポイントを最適化すること。\n${jobDescription}`
    : "";

  const user = `以下の職務経歴書をプレゼンテーション用スライドデータに変換してください。

対象者: ${settings.name}
応募先業界: ${settings.industry}
応募先職種: ${settings.jobType}
転職タイプ: ${settings.transferType}

【職務経歴書テキスト】
${resumeText}${jobSection}`;

  return { system, user };
}
