import { KNOWLEDGE_BASE } from "./knowledge-base";
import type { UserSettings, AppMode } from "./types";

export function buildSystemPrompt(
  settings: UserSettings,
  mode: AppMode
): string {
  const parts: string[] = [];

  // 1. RAGナレッジベース全文
  parts.push(KNOWLEDGE_BASE);

  // 2. セッション設定
  parts.push(`
---
# ■ セッション設定

- 対象年代: ${settings.ageGroup}
- 応募先業界: ${settings.industry}
- 応募先職種: ${settings.jobType}
- 転職タイプ: ${settings.transferType}への転職
- 対象者名: ${settings.name}
`);

  // 3. 転職タイプ別の分岐
  if (settings.transferType === "同業種") {
    parts.push(`
## 転職タイプ指示（同業種転職）
ユーザーは同業種転職を希望しています。${settings.industry}業界内での転職です。
- 業界特有の専門性と即戦力としての再現性を重点的にアピールしてください
- 業界用語は適切に使用し、技術的な深さを出してください
- 競合他社との差別化ポイントを意識した表現を用いてください
`);
  } else {
    parts.push(`
## 転職タイプ指示（異業種転職）
ユーザーは異業種転職を希望しています。${settings.industry}業界への転職です。
- ポータブルスキル（マネジメント・課題解決・折衝力・プロジェクト管理）を前面に出してください
- 業界用語は使わず、誰でもわかる言葉で成果を説明してください
- 「なぜ異業種に挑戦するのか」の動機付けを重視してください
- 「異なる視点を活かした価値創出」を訴求してください
`);
  }

  // 4. 年代別の分岐
  if (settings.ageGroup === "50代") {
    parts.push(`
## 年代別指示（50代）
PART 8の50代専用ガイドラインを全面適用してください。
- マネジメント力、専門性の深さ、再現性の3つの期待値を示す
- さらに次世代育成力、経営視点も重視する
- 数字による実績証明を強化する
- 「貢献期間のロードマップ」「育成実績」「変化対応力」「年下上司への適応」「謙虚さとプロ意識」の5要素を必ず意識する
- 年齢の壁を超える記述を積極的に盛り込む
`);
  } else if (settings.ageGroup === "40代") {
    parts.push(`
## 年代別指示（40代）
- マネジメント力、専門性の深さ、再現性の3つの期待値を明確に示してください
- 数字による実績証明を強化してください
- 即戦力としての価値を強調してください
`);
  } else {
    parts.push(`
## 年代別指示（${settings.ageGroup}）
- ポテンシャルと成長意欲を重視してください
- 学習速度と適応力をアピールしてください
- PREP法による自己PRを重視してください
`);
  }

  // 5. モード別の指示
  if (mode === "review") {
    parts.push(`
## モード指示（添削モード）
PART 7の添削出力フォーマットに厳密に従って回答してください。

出力順序:
1. 総合スコア
2. 軸別スコア（テーブル形式）
3. 総評（3〜5行）
4. 最優先改善ポイントTOP3
5. セクション別フィードバック（Before→After付き）
6. 改善版サンプル
7. 次のステップ
8. 応援メッセージ

重要: 応答の最後に以下のJSON形式でスコアを出力してください（フロントエンドでのパース用）:
<!-- SCORES_JSON:{"impact":XX,"specificity":XX,"targetFit":XX,"readability":XX,"emotion":XX,"total":XX} -->
`);
  } else if (mode === "rewrite") {
    parts.push(`
## モード指示（リライトモード）
職務経歴書フォーマットに準拠した全文を作成してください。

セクション構成:
- 【職務要約】
- 【職務経歴】（※全ての在籍企業を個別に記載。要約しすぎない）
- 【業務実績】
- 【自己PR】（PREP法を必ず使用）

★★★ 最重要ルール：文体・表現について ★★★

1.【各社の職務を省略しない】
  複数社経験がある場合、全ての会社の職務内容を個別に丁寧に記載すること。
  「要約」して1つにまとめてはいけない。読み手が各社での役割・成果を
  具体的にイメージできるよう、1社ごとに詳細を書く。

2.【硬い文章にしない・読み手がイメージしやすい表現を使う】
  官僚的・形式的な文体ではなく、具体的で映像が浮かぶ文章にする。
  「〜に従事」「〜を遂行」「〜を担当」の連発は禁止。

3.【抽象的なバズワードを使わない】
  「チームビルディング」「コミュニケーション能力」「リーダーシップ」
  などの使い勝手の良い抽象語は、書き手と読み手の認識がズレる。
  必ずもう1段かみ砕いた具体的な表現に変換すること。

  NG → OK の変換例：
  - 「コミュニケーション能力がある」→「相手が求めているものを理解し、対応することができる」
  - 「チームビルディングを推進」→「メンバー一人ひとりの強みを把握し、適材適所の役割配置で全員が力を発揮できる環境を作った」
  - 「リーダーシップを発揮」→「週次ミーティングで各メンバーの進捗と課題を確認し、障害を取り除くことでチーム全体の目標達成率を向上させた」
  - 「マネジメント経験」→「12名の部下の目標設定・進捗管理・評価面談を担当し、離職率を15%→3%に改善」
  - 「問題解決能力」→「顧客からのクレーム原因を現場で調査し、工程を見直して再発防止策を3日以内に実施」

4.【自己PRはPREP法を厳守】
  P（Point）：結論（私の強みは○○です）
  R（Reason）：理由（なぜなら○○だからです）
  E（Example）：具体例（実際に○○の場面で○○を行い、○○という成果を出しました）
  P（Point）：結論の再提示（この強みを活かして貴社で○○に貢献します）

重要制約:
- 虚偽の実績は絶対に創作しない
- 数字は元の情報にあるものだけ使う
- 改善ポイントの解説を末尾に添付する
`);
  } else {
    parts.push(`
## モード指示（自己PR作成モード）
PREP法（Point→Reason→Example→Point）の4構造で自己PRを作成してください。

★★★ PREP法の構造を厳守 ★★★
各自己PRは必ず以下の4パートで構成すること：

P（Point・結論）：私の強みは○○です。
R（Reason・理由）：なぜなら、○○の経験を通じて○○を身につけたからです。
E（Example・具体例）：実際に、○○という状況で○○を行い、○○という成果を出しました。
P（Point・結論の再提示）：この○○を活かし、貴社の○○に貢献したいと考えています。

★★★ 文体・表現の重要ルール ★★★
- 抽象的なバズワードを使わない
  NG：「コミュニケーション能力」「チームビルディング」「リーダーシップ」
  OK：具体的に何をしたか、何ができるかを書く
  例：「コミュニケーション能力がある」→「相手が求めているものを理解し、対応することができる」
- 読み手が映像としてイメージできる具体的な文章にする
- 硬い官僚的な文体を避け、人間味のある表現にする

要件:
- 400〜600字で作成
- 2〜3案を提示する
- 各案にはタイトルをつける
- 各案でPREP法の4パート（P→R→E→P）を明示的にラベル付けする
- 応募先の業界・職種に合わせた内容にする
- 虚偽の実績は絶対に創作しない
`);
  }

  // 6. 共通制約
  parts.push(`
## 共通制約
- 日本語で回答してください
- マークダウン形式で出力してください
- 虚偽の実績を創作しないでください
- 数字は元の情報にあるものだけ使ってください
- ユーザーの経歴にない経験を追加しないでください
`);

  return parts.join("\n");
}

export function buildUserMessage(
  mode: AppMode,
  resumeText: string,
  extraInfo: string
): string {
  const extra = extraInfo
    ? `\n\n【補足情報・応募先詳細】\n${extraInfo}`
    : "";

  switch (mode) {
    case "review":
      return `以下の職務経歴書を添削してください。5軸評価でスコアリングし、Before→Afterの改善案を提示してください。\n\n【職務経歴書】\n${resumeText}${extra}`;
    case "rewrite":
      return `以下の職務経歴書をリライトしてください。改善版の職務経歴書を全文作成してください。\n\n【職務経歴書】\n${resumeText}${extra}`;
    case "selfpr":
      return `以下の情報をもとにPREP法で自己PRを作成してください。400〜600字で2〜3案を提示してください。\n\n【経歴・強み・実績】\n${resumeText}${extra}`;
  }
}
